"""Base questions + phrasing variants for the robustness benchmark.

Each case is asked four ways — the original wording ("base") plus three
variants — and the agent's answers across all four are compared pairwise by
embedding cosine similarity (see run_benchmark.py). A robust agent should
answer with roughly the same content regardless of how the question is
phrased or what language it's asked in.

`expect_tool` / `expect_substrings` are a secondary, per-phrasing sanity
check reusing the same RuleScorer/ToolUsageScorer as every other benchmark
in this project — did the *content* stay right, not just "similar to the
other phrasings" (four confidently-wrong-in-the-same-way answers would
still score a perfect similarity). Substrings are deliberately restricted
to language-invariant content (numbers) — a proper noun like a place name
would come back in a different language for the Chinese phrasings than for
the English translation, and fail the check for the wrong reason.

Variant wording is pre-authored and static, not generated by an LLM at run
time — same reasoning as the RAG benchmark's lexical/paraphrase queries:
reproducible, and it avoids grading a translation the same system
implicitly produced. Base questions are Chinese, matching the other two
benchmarks; English was chosen as the one translation target rather than a
second non-English language to keep the set small while still crossing a
real language boundary.

Variants, per case:
  - base: the original Chinese wording.
  - paraphrase: same language, reworded — different vocabulary/structure.
  - register: formal/polite phrasing, or wrapped in an irrelevant courtesy
    preamble — tests whether surface politeness noise changes what the
    agent actually does.
  - translation: the same request in English.
"""

